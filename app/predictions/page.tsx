function lstmPred(allDraws: number[][]): number[] {
  const LH = 16, LIN = 43, LSEQ = 10;
  if (allDraws.length < LSEQ) return [];
  const lsig = (x: number) => 1 / (1 + Math.exp(-Math.max(-20, Math.min(20, x))));
  let lh = new Float64Array(LH);
  let lc = new Float64Array(LH);
  for (const draw of allDraws.slice(-LSEQ)) {
    const xh = new Float64Array(LIN + LH);
    for (const n of draw) xh[n - 1] = 1;
    xh.set(lh, LIN);
    const z = new Float64Array(4 * LH);
    for (let r = 0; r < 4 * LH; r++) {
      let s = LSTM_B[r];
      const base = r * (LIN + LH);
      for (let col = 0; col < LIN + LH; col++) s += LSTM_W[base + col] * xh[col];
      z[r] = s;
    }
    const cn = new Float64Array(LH);
    const hn = new Float64Array(LH);
    for (let j = 0; j < LH; j++) {
      const ig = lsig(z[j]),         fg = lsig(z[LH + j]);
      const og = lsig(z[2 * LH + j]), gg = Math.tanh(z[3 * LH + j]);
      cn[j] = fg * lc[j] + ig * gg;
      hn[j] = og * Math.tanh(cn[j]);
    }
    lh = hn; lc = cn;
  }
  const y = new Float64Array(LIN);
  for (let i = 0; i < LIN; i++) {
    let s = LSTM_BY[i];
    for (let j = 0; j < LH; j++) s += LSTM_WY[i * LH + j] * lh[j];
    y[i] = lsig(s);
  }
  return Array.from({ length: LIN }, (_, i) => ({ n: i + 1, p: y[i] }))
    .sort((a, b) => b.p - a.p).slice(0, 15).map(x => x.n).sort((a, b) => a - b);
}

